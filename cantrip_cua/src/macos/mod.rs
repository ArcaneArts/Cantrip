fn diagnostic_entry() -> bool {
    static ENABLED: OnceLock<bool> = OnceLock::new();
    static LINES: AtomicUsize = AtomicUsize::new(0);
    *ENABLED.get_or_init(|| {
        std::env::var_os("CANTRIP_CUA_NATIVE_DIAGNOSTICS").is_some_and(|value| value == "1")
    }) && LINES
        .fetch_update(Ordering::Relaxed, Ordering::Relaxed, |count| {
            (count < 256).then_some(count + 1)
        })
        .is_ok()
}

fn diagnostic_phase(phase: &'static str) {
    if diagnostic_entry() {
        eprintln!("{{\"event\":\"cua.native.phase\",\"phase\":\"{phase}\"}}");
    }
}

fn diagnostic_inventory_count(kind: &'static str, count: usize) {
    if diagnostic_entry() {
        eprintln!(
            "{}",
            serde_json::json!({"event":"cua.native.inventory.count", "kind":kind, "count":count})
        );
    }
}

fn diagnostic_candidate_rejection(kind: &'static str, error: &CuaError) {
    if diagnostic_entry() {
        // These errors are generated by our metadata validation, not native
        // localized descriptions; they contain no target identifiers or titles.
        eprintln!(
            "{}",
            serde_json::json!({"event":"cua.native.inventory.rejected", "kind":kind, "code":error.code, "message":error.message})
        );
    }
}

fn diagnostic_native_error(error: &NSError) {
    if diagnostic_entry() {
        let info = error.userInfo();
        let keys = info.allKeys();
        let keys: Vec<_> = (0..keys.count().min(16))
            .map(|index| geometry::bounded_text(keys.objectAtIndex(index).to_string(), 80))
            .collect();
        let underlying = info.objectForKey(unsafe { NSUnderlyingErrorKey }).and_then(|value| value.downcast_ref::<NSError>().map(|error| serde_json::json!({"domain": geometry::bounded_text(error.domain().to_string(), 120), "code": error.code()})));
        // Keys and numeric/domain identity only. Never error descriptions,
        // arbitrary userInfo values, URLs, paths, titles or screenshot bytes.
        eprintln!(
            "{}",
            serde_json::json!({"event":"cua.native.error", "code":error.code(), "domain":geometry::bounded_text(error.domain().to_string(), 120), "keys":keys, "underlying":underlying})
        );
    }
}

