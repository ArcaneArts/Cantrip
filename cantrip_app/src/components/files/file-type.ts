/** Match basenames only, on every host platform; names beat generic extensions. */
export function fileIconKindForPath(path: string): FileIconKind {
  const name =
    path.replaceAll("\\", "/").split("/").at(-1)?.toLowerCase() ?? "";
  const known = Object.hasOwn(filenames, name) ? filenames[name] : undefined;
  if (known) return known;
  if (name === ".env" || name.startsWith(".env.")) return "config";
  if (/^(?:dockerfile|containerfile)\./u.test(name)) return "docker";
  if (/^(?:licen[cs]e|copying)(?:[.-]|$)/u.test(name)) return "license";
  const dot = name.lastIndexOf(".");
  const extension = dot > 0 ? name.slice(dot + 1) : "";
  return Object.hasOwn(extensions, extension) ? extensions[extension]! : "file";
}
